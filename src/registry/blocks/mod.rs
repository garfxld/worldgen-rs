#[derive(Debug, Clone, Copy, PartialEq)]
pub struct BlockStateMetadata {
    fluid: FluidRef,
    amount: u8,
    flags: u8,
}

impl BlockStateMetadata {
    const FALLING: u8 = 1 << 0;
    const IS_AIR: u8 = 1 << 1;
    const HAS_FLUID: u8 = 1 << 2;

    pub const fn new(fluid_state: FluidState, is_air: bool) -> Self {
        let mut flags = 0;
        if fluid_state.falling {
            flags |= Self::FALLING;
        }
        if is_air {
            flags |= Self::IS_AIR;
        }
        if !fluid_state.is_empty() {
            flags |= Self::HAS_FLUID;
        }
        Self {
            fluid: fluid_state.fluid_id,
            amount: fluid_state.amount,
            flags,
        }
    }

    pub const fn fluid_state(self) -> FluidState {
        FluidState::new(self.fluid, self.amount, self.flags & Self::FALLING != 0)
    }

    pub const fn is_air(self) -> bool {
        self.flags & Self::IS_AIR != 0
    }

    pub const fn has_fluid(self) -> bool {
        self.flags & Self::HAS_FLUID != 0
    }
}

pub struct Block {
    pub key: Identifier,
    pub config: BlockConfig,
    pub properties: &'static [&'static dyn Property],
    pub default_state_offset: u16,
    pub suffocating: StateBooleanData,
    pub redstone_conductor: StateBooleanData,
    pub fluid_state: StateFluidData,
    pub light_properties: LightPropertiesFn,
    pub collision_shape: ShapeFn,
    pub support_shape: ShapeFn,
    pub outline_shape: ShapeFn,
    pub occlusion_shape: ShapeFn,
    pub shape_offsets: shapes::ShapeOffsetFlags,
    pub id: OnceLock<usize>,
}

impl Debug for Block {
    fn fmt(&self, f: &mut Formatter<'_>) -> fmt::Result {
        f.debug_struct("Block")
            .field("key", &self.key)
            .field("config", &self.config)
            .field("properties", &self.properties)
            .field("default_state_offset", &self.default_state_offset)
            .finish_non_exhaustive()
    }
}

impl PartialEq for Block {
    fn eq(&self, other: &Self) -> bool {
        self.key == other.key
    }
}

impl Eq for Block {}

